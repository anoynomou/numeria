export const WORLD_BY_ID = Object.fromEntries(WORLDS.map((w) => [w.id, w]));

/** Which world a given level number (1-10) takes place in. */
export function worldForLevel(level) {
  const n = Math.min(10, Math.max(1, Number(level) || 1));
  return WORLDS.find((w) => w.levels.includes(n)) || WORLDS[0];
}

/** Lowest level number that unlocks a world. */
export function unlockLevelFor(worldId) {
  const w = WORLD_BY_ID[worldId];
  return w ? w.levels[0] : 1;
}
